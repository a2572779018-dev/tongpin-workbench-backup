"""Generate the exact Unicode tables the OpenSquilla router's Python stack uses.

The V4.2 router features are computed with CPython ``re``/``str`` semantics and
the BGE tokenizer with Hugging Face ``tokenizers`` (Rust).  JavaScript engines
differ in several places (``\\s``/``\\w``/``\\d`` classes, ``str.split``,
``str.lower`` special cases, and the Unicode tables ``tokenizers`` was built
with), so the TypeScript port reads these tables instead of the host engine's.
Every table is produced by probing the reference runtime itself, one code
point at a time, rather than from documentation.

Usage: python gen_unicode_tables.py --tokenizer <bundle>/bge_onnx/tokenizer.json --out <ts file>
"""

from __future__ import annotations

import argparse
import platform
import re
import sys
import unicodedata

from tokenizers import Tokenizer

MAX_CP = 0x110000


def code_points():
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in code_points():
        if predicate(cp):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            elif out and out[-1][1] == 0xD7FF and cp == 0xE000:
                # surrogates are never text code points; keep ranges contiguous
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def encode(rs: list[tuple[int, int]]) -> str:
    return ",".join(f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in rs)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tokenizer", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    space = re.compile(r"\s")
    for cp in code_points():
        ch = chr(cp)
        if bool(space.match(ch)) != ch.isspace():
            raise SystemExit(f"re \\s differs from str.isspace at U+{cp:04X}")

    lower_map: dict[int, str] = {}
    for cp in code_points():
        if cp == 0x3A3:
            continue  # context-dependent final sigma, handled explicitly
        lowered = chr(cp).lower()
        if lowered != chr(cp):
            lower_map[cp] = lowered
    # Final-sigma context tables, probed through str.lower itself.
    cased = ranges(lambda cp: ("AΣ" + chr(cp)).lower()[1] == "σ" and cp != 0x3A3)
    cased_set = {cp for a, b in cased for cp in range(a, b + 1)}
    ignorable = ranges(lambda cp: cp not in cased_set and cp != 0x3A3 and ("A" + chr(cp) + "Σ").lower()[-1] == "ς")

    tokenizer = Tokenizer.from_file(args.tokenizer)
    normalizer = tokenizer.normalizer
    pre_tokenizer = tokenizer.pre_tokenizer
    removed, whitespace, chinese = [], [], []
    for cp in code_points():
        ch = chr(cp)
        out = normalizer.normalize_str(ch)
        if out == ch:
            continue
        if out == "":
            removed.append(cp)
        elif out == " ":
            whitespace.append(cp)
        elif out == f" {ch} ":
            chinese.append(cp)
        else:
            raise SystemExit(f"unexpected normalizer output at U+{cp:04X}: {out!r}")
    removed_set, whitespace_set = set(removed), set(whitespace)

    def punctuation(cp: int) -> bool:
        if cp in removed_set or cp in whitespace_set:
            return False
        pieces = [piece for piece, _ in pre_tokenizer.pre_tokenize_str("a" + chr(cp) + "b")]
        if pieces == ["a" + chr(cp) + "b"]:
            return False
        if pieces == ["a", chr(cp), "b"]:
            return True
        if pieces == ["a", "b"] and cp == 0x20:
            return False  # the only whitespace left after normalization
        raise SystemExit(f"unexpected pre-tokenizer split at U+{cp:04X}: {pieces!r}")

    def as_ranges(values: list[int]) -> list[tuple[int, int]]:
        values_set = set(values)
        return ranges(lambda cp: cp in values_set)

    tables = {
        "PY_SPACE": ranges(lambda cp: chr(cp).isspace()),
        "PY_WORD": ranges(lambda cp: bool(word.match(chr(cp)))),
        "PY_DIGIT": ranges(lambda cp: bool(digit.match(chr(cp)))),
        "PY_CASED": cased,
        "PY_CASE_IGNORABLE": ignorable,
        "BERT_REMOVED": as_ranges(removed),
        "BERT_WHITESPACE": as_ranges(whitespace),
        "BERT_CHINESE": as_ranges(chinese),
        "BERT_PUNCTUATION": ranges(punctuation),
    }
    import tokenizers
    lines = [
        "// GENERATED by scripts/opensquilla-router/gen_unicode_tables.py — do not edit.",
        f"// CPython {platform.python_version()} (unicodedata {unicodedata.unidata_version}), tokenizers {tokenizers.__version__}.",
        "// Ranges are inclusive hex code point pairs, probed from the reference runtime.",
        "/* eslint-disable */",
    ]
    for name, rs in tables.items():
        lines.append(f'export const {name} = "{encode(rs)}";')
    lower_items = ",".join(
        f"{cp:x}:" + ".".join(f"{ord(c):x}" for c in value) for cp, value in sorted(lower_map.items())
    )
    lines.append(f'export const PY_LOWER = "{lower_items}";')
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    sizes = {name: len(rs) for name, rs in tables.items()}
    print(f"wrote {args.out}: {sizes}, lower={len(lower_map)}", file=sys.stderr)


if __name__ == "__main__":
    main()
