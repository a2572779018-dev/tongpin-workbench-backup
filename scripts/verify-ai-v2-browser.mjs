/** Real page and React component with synthetic transport only. */
import assert from "node:assert/strict";
const playwright = await import(process.env.TONGPIN_PLAYWRIGHT_MODULE ?? "playwright");
const { chromium } = playwright.default ?? playwright;
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1360, height: 950 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:5182/scripts/ai-v2-acceptance.html?run=${crypto.randomUUID()}`);
  await page.getByRole("button", { name: "新建对话", exact: true }).first().click();
  await page.getByLabel("对话名称").fill("A 会话");
  await page.getByRole("button", { name: "新建对话", exact: true }).last().click();
  await page.locator("textarea").fill("A 的第一个问题");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  await page.locator(".tp-ai-message").getByText("V2 回复：A 会话 / A 的第一个问题").waitFor();
  await page.locator('input[aria-label="选择附件文件"]').setInputFiles({ name: "A.txt", mimeType: "text/plain", buffer: Buffer.from("只属于 A 的资料") });
  await page.getByRole("button", { name: "移除附件 A.txt" }).waitFor();
  await page.locator("textarea").fill("结合资料继续");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  await page.locator(".tp-ai-message").getByText("V2 回复：A 会话 / 结合资料").waitFor();
  assert.match(await page.getByLabel("V2 验收证据").innerText(), /model:conversation-[\w-]+:1/);
  await page.getByRole("button", { name: "新对话", exact: true }).click();
  await page.getByLabel("对话名称").fill("B 会话");
  await page.getByRole("button", { name: "新建对话", exact: true }).last().click();
  await page.getByRole("button", { name: "B 会话", exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll(".tp-ai-v2-conversation button.is-active")].some(button => button.textContent?.includes("B 会话")));
  await page.locator("textarea").fill("B 的问题");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  await page.locator(".tp-ai-message").getByText("V2 回复：B 会话 / B 的问题").waitFor();
  await page.getByRole("button", { name: "A 会话", exact: true }).click();
  await page.locator(".tp-ai-message").getByText("V2 回复：A 会话 / A 的第一个问题").waitFor();
  await page.getByText("A.txt", { exact: true }).waitFor();
  await page.locator("textarea").fill("A 重开后的草稿");
  await page.waitForTimeout(700);
  await page.reload();
  await page.getByRole("button", { name: "A 会话", exact: true }).click();
  await page.waitForFunction(() => document.querySelector("textarea")?.value === "A 重开后的草稿");
  assert.equal(await page.locator("textarea").inputValue(), "A 重开后的草稿");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  await page.locator(".tp-ai-message").getByText("V2 回复：A 会话 / A 重开后的草稿").waitFor();
  await page.getByRole("button", { name: "B 会话", exact: true }).click();
  assert.equal(await page.locator(".tp-ai-message").getByText("V2 回复：A 会话 / A 重开后的草稿").count(), 0);
  await page.locator(".tp-ai-message").getByText("V2 回复：B 会话 / B 的问题").waitFor();
  const log = await page.getByLabel("V2 验收证据").innerText();
  assert.ok(!log.includes("FORBIDDEN_V1_WORKSPACE"), log);
  assert.ok(log.includes("read-page:") && log.includes("model:"));
  assert.deepEqual(errors, []);
  const history = await browser.newPage({ viewport: { width: 1360, height: 950 } });
  await history.goto(`http://127.0.0.1:5182/scripts/ai-v2-acceptance.html?run=${crypto.randomUUID()}&history`);
  await history.getByText("历史消息 64").waitFor();
  assert.equal(await history.getByText("历史消息 0").count(), 0);
  await history.getByRole("button", { name: "加载更早的消息", exact: true }).click();
  await history.waitForFunction(() => document.querySelector('output[aria-label="V2 验收证据"]')?.textContent?.includes("read-page:history-chat:5:35"));
  assert.equal(await history.getByText("历史消息 64").count(), 1);
  await history.close();
  console.log(JSON.stringify({ result: "V2 local synthetic UI path passed", conversations: 2, reload: true, pagedHistory: true, attachments: true, v1WorkspaceReads: 0 }));
} finally { await browser.close(); }
